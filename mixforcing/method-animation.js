/* Original PDF artwork is preserved as SVG; animation only overlays its flow. */
(() => {
  'use strict';

  function initMethodAnimation() {
    const root = document.getElementById('method-animation');
    if (!root) return;

    const phases = ['condition', 'generate', 'decode', 'cache'];
    const durations = [950, 1300, 1100, 850];
    const modelX = [171.2817, 450.0819, 728.8822];
    const rect = (x, y, w, h, cls, radius = 5) => `<rect class="${cls}" x="${x}" y="${y}" width="${w}" height="${h}" rx="${radius}"/>`;
    const flow = (x1, y1, x2, y2, cls, radius = 6) => `<g class="diagram-flow ${cls}"><circle class="diagram-packet" cx="${x1}" cy="${y1}" r="${radius}" style="--packet-x:${x2 - x1}px;--packet-y:${y2 - y1}px"/></g>`;

    root.innerHTML = `
      <div class="method-canvas-scroll" tabindex="0" role="region" aria-label="Pipeline and training attention masks; scroll horizontally on small screens">
        <svg class="method-canvas" viewBox="0 0 1530 455" xmlns="http://www.w3.org/2000/svg" role="group" aria-labelledby="animated-method-title animated-method-desc">
          <title id="animated-method-title">Mix Forcing pipeline and MoBA training masks</title>
          <desc id="animated-method-desc">Original pipeline artwork. Each chunk receives a pose and local prompt, is generated by the shared causal video model, and is decoded by a VAE. Two diagonal magnification lines connect the last model box to the MoBA self-attention and cross-attention masks used during causal pre-training.</desc>
          <defs>
            <linearGradient id="model-scan-gradient"><stop offset="0" stop-color="#b6acd8" stop-opacity="0"/><stop offset=".5" stop-color="#b6acd8" stop-opacity=".85"/><stop offset="1" stop-color="#b6acd8" stop-opacity="0"/></linearGradient>
            ${modelX.map((x, i) => `<clipPath id="model-scan-clip-${i}">${rect(x + 2, 182.562, 218.11, 68, '', 4.06)}</clipPath>`).join('')}
          </defs>
          <text class="diagram-heading" x="10" y="35">Autoregressive video generation</text>
          <g transform="translate(10 70)">
            <image href="assets/figures/method-pipeline.svg" width="1049" height="354"/>
            <g class="diagram-overlays" aria-hidden="true">
              ${rect(171.2817, 316.98685, 779.71, 29.08, 'diagram-environment')}
              ${modelX.map((x, i) => `<g class="diagram-chunk" data-diagram-chunk="${i}">
                <g class="diagram-future-veil">
                  ${rect(x + 1, 181.562, 220.11, 70, '', 5.06)}
                  ${rect(x + 1, 281.37053, 71.66, 27.08, '', 3.85)}
                  ${rect(x + 82.9718, 281.37053, 138.14, 27.08, '', 3.85)}
                </g>
                ${rect(x, 180.562, 222.11, 72, 'diagram-model', 6.06)}
                ${rect(x, 280.37053, 73.66, 29.08, 'diagram-input')}
                ${rect(x + 81.9718, 280.37053, 140.14, 29.08, 'diagram-input')}
                ${rect(x + 7.0625, 8.3071, 208, 120.09, 'diagram-output', 4)}
                <g class="diagram-output-cover" style="--output-left:${x + 7.0625}px;--output-top:8.3071px">
                  ${rect(x + 7.0625, 8.3071, 208, 120.09, 'diagram-output-placeholder', 4)}
                  <text x="${x + 111.0625}" y="63" text-anchor="middle">Video chunk ${i + 1}</text>
                  <text class="diagram-wait-label" x="${x + 111.0625}" y="84" text-anchor="middle">Waiting to generate</text>
                </g>
                <g class="diagram-model-scan" clip-path="url(#model-scan-clip-${i})">
                  <rect class="diagram-scan-beam" x="${x - 60}" y="182.562" width="60" height="68"/>
                </g>
                <rect class="diagram-model-progress" x="${x + 12}" y="241" width="198" height="6" rx="3" style="transform-origin:${x + 12}px 244px"/>
                ${flow(x + 36.83, 274, x + 36.83, 267, 'diagram-condition', 3.5)}
                ${flow(x + 152.043, 274, x + 152.043, 267, 'diagram-condition', 3.5)}
                ${flow(x + 110.414, 150, x + 110.414, 142, 'diagram-decode', 3.5)}
                ${i === 0 ? flow(137, 216.5625, 153, 216.5625, 'diagram-condition') : ''}
                ${i > 0 ? flow(modelX[i - 1] + 231.11, 216.5625, x - 18, 216.5625, 'diagram-condition') : ''}
                ${flow(x + 231.11, 216.5625, i < 2 ? modelX[i + 1] - 18 : 983, 216.5625, 'diagram-cache')}
              </g>`).join('')}
            </g>
            ${modelX.map((x, i) => `<a href="assets/figures/moba.pdf" class="diagram-model-link" data-open-mask aria-label="Inspect the MoBA training masks for causal video model ${i + 1}">${rect(x, 180.562, 222.11, 72, 'diagram-model-hit', 6.06)}</a>`).join('')}
          </g>
          <g class="diagram-callout-lines" aria-hidden="true">
            <path d="M960.99 250.562L1110 72M960.99 322.562L1110 407"/>
          </g>
          <a class="diagram-mask-link" href="assets/figures/moba.pdf" data-open-mask aria-label="Enlarge MoBA attention masks used during training">
            <rect class="diagram-mask-frame" x="1110" y="72" width="405" height="335" rx="8"/>
            <text class="diagram-mask-heading" x="1126" y="98">MoBA attention masks</text>
            <text class="diagram-mask-subtitle" x="1126" y="119">Used during causal pre-training</text>
            <image href="assets/figures/moba-mask.svg" x="1125" y="136" width="375" height="256.24"/>
            <text class="diagram-expand" x="1485" y="98" aria-hidden="true">↗</text>
          </a>
        </svg>
      </div>
      <div class="method-animation-readout" aria-hidden="true">
        <span class="method-current-chunk">Chunk 1 / 3</span>
        <ol class="method-stages">${['Condition', 'Generate', 'Decode', 'Cache'].map((label, i) => `<li>${i ? '<span class="method-stage-arrow">→</span>' : ''}<span data-stage="${i}">${label}</span></li>`).join('')}</ol>
      </div>
      <p class="method-animation-status" aria-live="off" aria-atomic="true"></p>
      <p class="method-pan-hint">Swipe to see the full diagram.</p>
      <dialog class="moba-dialog" aria-labelledby="moba-dialog-title">
        <div class="moba-dialog-heading"><div><h3 id="moba-dialog-title">MoBA attention masks</h3><p>Used to pretrain the shared causal video model.</p></div><button type="button" class="moba-close" aria-label="Close attention mask">×</button></div>
        <img src="assets/figures/moba-mask.svg" width="581" height="397" alt="MoBA training masks: teacher-forcing chunks attend to clean history and themselves, while the bidirectional branch is isolated. Cross-attention uses the environment and matching local prompt for teacher forcing, and the global prompt for the bidirectional branch.">
        <div class="moba-dialog-caption"><p><strong>Self-attention:</strong> teacher forcing learns causal prediction; the isolated bidirectional branch preserves visual priors.</p><p><strong>Cross-attention:</strong> TF chunks use the shared environment prompt and their own local prompt. BID chunks use the global prompt.</p><a href="assets/figures/moba.pdf" target="_blank" rel="noopener">Open original PDF ↗</a></div>
      </dialog>`;

    const chunks = [...root.querySelectorAll('.diagram-chunk')];
    const stageLabels = [...root.querySelectorAll('[data-stage]')];
    const status = root.querySelector('.method-animation-status');
    const dialog = root.querySelector('.moba-dialog');
    const motion = window.matchMedia('(prefers-reduced-motion: reduce)');
    let step = 0;
    let visible = false;
    let timer = null;
    let dialogTrigger = null;

    function isPlaying() {
      return visible && !document.hidden && !motion.matches && !dialog.open;
    }

    function render() {
      const chunk = Math.floor(step / 4);
      const phase = step % 4;
      const playing = isPlaying();
      root.dataset.phase = phases[phase];
      root.dataset.chunk = String(chunk + 1);
      root.classList.toggle('is-playing', playing);
      root.classList.toggle('is-reduced-motion', motion.matches);
      chunks.forEach((column, i) => {
        column.classList.toggle('is-current', i === chunk);
        column.classList.toggle('is-complete', i < chunk);
        column.classList.toggle('is-future', i > chunk);
        column.classList.toggle('is-revealed', i < chunk || (i === chunk && phase >= 2));
        column.querySelector('.diagram-wait-label').textContent = i === chunk && phase === 1
          ? 'Generating latent…' : 'Waiting to generate';
      });
      stageLabels.forEach((label, i) => label.classList.toggle('is-current', i === phase));
      root.querySelector('.method-current-chunk').textContent = `Chunk ${chunk + 1} / 3`;
      const history = chunk === 0 ? 'the initial image' : 'cached history';
      const descriptions = [
        `Chunk ${chunk + 1} · Condition on ${history}, the environment prompt, and the current pose and local prompt.`,
        `Chunk ${chunk + 1} · The pretrained causal model generates the next latent chunk.`,
        `Chunk ${chunk + 1} · VAE decode turns the latent chunk into video.`,
        `Chunk ${chunk + 1} · Reuse the KV cache for the next chunk, without recomputing earlier history.`
      ];
      status.textContent = motion.matches
        ? 'Each chunk uses current inputs and cached history, then the VAE decodes it into video.'
        : descriptions[phase];
    }

    function schedule() {
      window.clearTimeout(timer);
      timer = null;
      render();
      if (!isPlaying()) return;
      timer = window.setTimeout(() => {
        step = (step + 1) % 12;
        if (step % 4 === 0) revealCurrentChunk();
        schedule();
      }, durations[step % 4] + (step === 11 ? 1200 : 0));
    }

    function revealCurrentChunk() {
      const viewport = root.querySelector('.method-canvas-scroll');
      if (viewport.scrollWidth > viewport.clientWidth + 1) {
        const scale = root.querySelector('.method-canvas').getBoundingClientRect().width / 1530;
        const center = (modelX[Math.floor(step / 4)] + 121) * scale;
        viewport.scrollTo({ left: Math.max(0, center - viewport.clientWidth / 2), behavior: motion.matches ? 'instant' : 'smooth' });
      }
    }

    root.querySelectorAll('[data-open-mask]').forEach(trigger => trigger.addEventListener('click', event => {
      event.preventDefault();
      dialogTrigger = trigger;
      dialog.showModal();
      schedule();
    }));
    root.querySelector('.moba-close').addEventListener('click', () => dialog.close());
    dialog.addEventListener('click', event => {
      const bounds = dialog.getBoundingClientRect();
      if (event.target === dialog && (event.clientX < bounds.left || event.clientX > bounds.right || event.clientY < bounds.top || event.clientY > bounds.bottom)) dialog.close();
    });
    dialog.addEventListener('close', () => {
      dialogTrigger?.focus({ preventScroll: true });
      schedule();
    });
    document.addEventListener('visibilitychange', schedule);
    window.addEventListener('pagehide', () => window.clearTimeout(timer));
    window.addEventListener('pageshow', schedule);
    motion.addEventListener('change', schedule);

    root.hidden = false;
    root.parentElement.querySelector('.method-static').hidden = true;
    if ('IntersectionObserver' in window) {
      new IntersectionObserver(entries => {
        visible = entries[0].isIntersecting && entries[0].intersectionRatio >= 0.12;
        schedule();
      }, { threshold: [0, 0.12] }).observe(root);
    } else visible = true;
    schedule();
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initMethodAnimation, { once: true });
  } else initMethodAnimation();
})();
